/**
 * Starter food library — sourced from UK CoFID 2021
 * (McCance & Widdowson's Composition of Foods Integrated Dataset, Public Health England).
 * https://www.gov.uk/government/publications/composition-of-foods-integrated-dataset-cofid
 *
 * CONVENTIONS — read before editing:
 *  • `carbs` is AVAILABLE carbohydrate (monosaccharide equivalents). Fibre is NOT
 *    inside it; it has its own field. This is the UK convention, not the US
 *    "total carbohydrate" one.
 *  • `fibre` is AOAC fibre. `null` means CoFID did not measure it for that food —
 *    deliberately null rather than 0, so we never claim a food is fibre-free when
 *    we simply don't know.
 *  • `calories` is CoFID's PUBLISHED energy value, scaled to the serving. CoFID
 *    computes energy as 4·protein + 3.75·carb + 9·fat with NO fibre credit
 *    (verified across 1425 rows, median deviation 0.14%). A UK product LABEL uses
 *    a different formula — 4·protein + 4·carb + 9·fat + 2·fibre — so a scanned
 *    barcode may read slightly higher than the library entry for fibrous foods.
 *    We cite CoFID's figure rather than deriving our own, to keep provenance intact.
 *  • Values are per the stated serving, already scaled from per-100g.
 *  • Meat/fish are RAW weight unless the name says otherwise (matches how you weigh
 *    them from the packet). Rice/oats/pasta are DRY weight. Bone-in foods use the
 *    EDIBLE portion, never "weighed with bone".
 *
 * These are typical composition values, not a specific product. For branded goods
 * the packet label is more accurate — scan it, correct the entry, and your saved
 * version takes priority.
 *
 * Generated file. To regenerate, see the CoFID extraction script in the scratchpad.
 */

