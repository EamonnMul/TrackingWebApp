/** Case-insensitive substring search over the library. */
export function searchStarterFoods(query: string, limit = 25): StarterFood[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const hits = STARTER_FOODS.filter(f =>
    f.name.toLowerCase().includes(q) || f.cofidName.toLowerCase().includes(q));
  // Prefer names that start with the query, then shorter names.
  hits.sort((a, b) => {
    const as = a.name.toLowerCase().startsWith(q) ? 0 : 1;
    const bs = b.name.toLowerCase().startsWith(q) ? 0 : 1;
    return as - bs || a.name.length - b.name.length;
  });
  return hits.slice(0, limit);
}
